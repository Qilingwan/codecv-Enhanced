import { chromium } from '/app/server/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror', e=>errors.push(e.message));
const exports=[];
page.on('request', req=>{if(req.url().includes('/api/export')) exports.push(req.url())});
await page.goto('http://127.0.0.1/#/editor?type=10front_end');
await page.locator('.cm-content').waitFor();
await page.locator('.driver-popover-close-btn').click();
await page.locator('.cm-content').click();
await page.keyboard.press('Control+a');
await page.keyboard.insertText('## 修复验证：李明\n\nicon:phone 13800138000\n\n## 项目经历\n\n- 修改后的中文内容：Docker 本地导出成功。\n- 支持 **加粗**、[项目链接](https://github.com/acmenlei/codecv) 和图标。\n\n## 专业技能\n\n- Vue / TypeScript / Docker');
await page.waitForTimeout(500);
assert.match(await page.locator('.reference-dom').first().innerText(),/修复验证：李明/);
const downloading=page.waitForEvent('download', {timeout:45000});
await page.getByRole('button',{name:'导出PDF',exact:true}).click();
const download=await downloading;
await download.saveAs('/tmp/edited-resume.pdf');
console.log('PDF UI download:',download.suggestedFilename());
await page.getByText('导入/导出',{exact:true}).hover();
const pngDownloading=page.waitForEvent('download',{timeout:45000});
await page.getByText('导出图片',{exact:true}).click();
await (await pngDownloading).saveAs('/tmp/edited-resume.png');
await page.screenshot({path:'/tmp/edited-editor.png',fullPage:true});
assert.equal(errors.length,0,errors.join('\n'));
assert.equal(exports.length,2);
console.log('Edited content rendered; PDF button and PNG client passed; page errors:',errors.length);
await browser.close();
